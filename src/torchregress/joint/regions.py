class JointConformal:
    r"""Split conformal calibration of a :class:`ConformalScore`.

    ``calibrate`` stores the thresholds; ``region`` turns them into a
    :class:`JointRegion` for new rows.  See the module docstring for the
    guarantee, its assumptions and the weighted and Mondrian variants.

    The thresholds are those of the shipped helpers of
    :mod:`torchregress.losses.conformal`
    (:func:`~torchregress.losses.conformal.finite_sample_quantile` unweighted, the
    Tibshirani et al. augmented quantile weighted), so they equal what
    :class:`~torchregress.losses.MultivariateScoreConformal` computes for the
    same scores.  The rank ``ceil((n + 1)(1 - alpha))`` is evaluated in floating
    point, where ``(n + 1)(1 - alpha)`` can land just above an integer; the rule
    then takes the next order statistic (conservative by one rank).

    Args:
        score: The conformity score.
        alpha: Miscoverage level, or several (regions nested in that order).

    Attributes:
        thresholds_: ``[L]``, or ``[G, L]`` with groups (levels in the order of
            ``alpha``).  With weights, the threshold for a test point whose
            weight equals the mean calibration weight of its group (``region``
            recomputes it per row from ``test_weights``).
        group_ids_: Sorted group ids ``[G]`` (with groups; empty when every
            calibration row was dropped, and every test group is then unseen).
        n_calibration_: Rows used (rows with nothing observed are dropped).
    """

    def __init__(self, score: ConformalScore, alpha: Union[float, Sequence[float]] = 0.1) -> None:
        if isinstance(alpha, (int, float)):
            alphas: tuple[float, ...] = (float(alpha),)
            self._scalar = True
        else:
            alphas = tuple(float(a) for a in alpha)
            self._scalar = False
        if not alphas or any(not 0.0 < a < 1.0 for a in alphas):
            raise ValueError(f"alpha must lie in (0, 1), got {alpha}")
        self.score = score
        self.alpha = alpha
        self._alphas = alphas
        self._fitted = False

    def calibrate(
        self,
        predictive: JointPredictive,
        y: Tensor,
        *,
        mask: Optional[Tensor] = None,
        weights: Optional[Tensor] = None,
        groups: Optional[Tensor] = None,
    ) -> "JointConformal":
        """Compute the thresholds from calibration rows.

        Args:
            predictive: Predictive of the calibration rows.
            y: Observed targets ``[n, d]``.
            mask: Boolean ``[n, d]`` (``True`` = observed) for missing
                calibration targets.  Only for scores with ``supports_mask``
                (and, for :class:`DensityScore`, predictives with
                ``exact_marginals``).  Rows with nothing observed are dropped.
                The guarantee then holds for test points with the same
                missingness mechanism.
            weights: Non-negative ``[n]`` for weighted split conformal.
            groups: Integer ``[n]`` group ids for Mondrian calibration.
        """
        self.score.check(predictive)
        y = _check_y(predictive, y)
        if y.dim() != 2:
            raise ValueError(f"calibration y must be [n, d], got {tuple(y.shape)}")
        n = predictive.batch_size
        if mask is not None:
            self.score.check_mask(predictive)
            mask = _check_mask(predictive, mask, y)
        if weights is not None:
            weights = torch.as_tensor(weights)
            if weights.shape != (n,):
                raise ValueError(f"weights must be [n] = [{n}], got {tuple(weights.shape)}")
            if not bool(torch.isfinite(weights).all()) or bool((weights < 0).any()):
                raise ValueError("weights must be finite and non-negative")
        if groups is not None:
            groups = torch.as_tensor(groups)
            if groups.shape != (n,) or groups.is_floating_point() or groups.dtype == torch.bool:
                raise ValueError(f"groups must be an integer [n] = [{n}] tensor")

        with torch.no_grad():
            scores = self.score._evaluate(predictive, y, mask, self.score._prepare(predictive))
        scores = _nan_as_inf(scores)  # a failed score counts as atypical (see JointRegion)
        keep = mask.any(-1) if mask is not None else torch.ones_like(scores, dtype=torch.bool)
        scores = scores[keep]
        g = (
            groups.to(scores.device)[keep].long()
            if groups is not None
            else torch.zeros_like(scores, dtype=torch.long)
        )
        w = weights.to(scores.device, torch.float64)[keep] if weights is not None else None

        self.group_ids_ = torch.unique(g, sorted=True)
        self._scores: list[Tensor] = []
        self._weights: list[Optional[Tensor]] = []
        rows = []
        for gid in self.group_ids_:
            sel = g == gid
            self._scores.append(scores[sel])
            if w is None:
                self._weights.append(None)
                rows.append(_order_stat_thresholds(scores[sel], self._alphas))
            else:
                self._weights.append(w[sel])
                # Reference threshold: a test point with the mean calibration weight.
                rows.append(_weighted_thresholds(scores[sel], w[sel], None, self._alphas)[0])
        if not rows:  # every row dropped
            rows.append(
                torch.full((len(self._alphas),), math.inf, dtype=scores.dtype, device=scores.device)
            )
            self._scores.append(scores[:0])
            self._weights.append(None if w is None else w[:0])
        table = torch.stack(rows)
        self.thresholds_ = table if groups is not None else table[0]
        self.n_calibration_ = int(keep.sum())
        self._grouped = groups is not None
        self._weighted = weights is not None
        self._masked = mask is not None
        self._fitted = True
        return self

    def region(
        self,
        predictive: JointPredictive,
        *,
        test_weights: Optional[Tensor] = None,
        groups: Optional[Tensor] = None,
    ) -> "JointRegion":
        """Regions for the rows of ``predictive``.

        Args:
            predictive: Predictive of the test rows.
            test_weights: Non-negative ``[n]`` test weights (required after a
                weighted calibration).
            groups: Integer ``[n]`` group ids (required after a Mondrian
                calibration).  A group unseen in calibration gets ``+inf``.
        """
        if not self._fitted:
            raise RuntimeError("call calibrate() before region()")
        self.score.check(predictive)
        n = predictive.batch_size
        device = self.thresholds_.device
        dtype = self.thresholds_.dtype
        n_levels = len(self._alphas)

        if self._grouped:
            if groups is None:
                raise ValueError("calibrated with groups: pass groups= to region()")
            groups = torch.as_tensor(groups)
            if groups.shape != (n,) or groups.is_floating_point():
                raise ValueError(f"groups must be an integer [n] = [{n}] tensor")
            ids = self.group_ids_
            g = groups.to(device).long()
            if ids.numel() == 0:  # every calibration row was dropped: no group is known
                idx = torch.zeros(n, dtype=torch.long, device=device)
                known = torch.zeros(n, dtype=torch.bool, device=device)
            else:
                idx = torch.searchsorted(ids, g).clamp(max=ids.numel() - 1)
                known = ids[idx] == g
        else:
            if groups is not None:
                raise ValueError("groups= given but calibration had no groups")
            idx = torch.zeros(n, dtype=torch.long, device=device)
            known = torch.ones(n, dtype=torch.bool, device=device)

        if self._weighted:
            if test_weights is None:
                raise ValueError("calibrated with weights: pass test_weights= to region()")
            test_weights = torch.as_tensor(test_weights)
            if test_weights.shape != (n,) or bool((test_weights < 0).any()):
                raise ValueError(f"test_weights must be non-negative [n] = [{n}]")
            tw = test_weights.to(device, torch.float64)
            threshold = torch.full((n, n_levels), math.inf, dtype=dtype, device=device)
            for gi in range(len(self._scores)):
                rows = (idx == gi) & known
                w_g = self._weights[gi]
                if not bool(rows.any()) or w_g is None:
                    continue
                threshold[rows] = _weighted_thresholds(
                    self._scores[gi], w_g, tw[rows], self._alphas
                ).to(dtype)
        else:
            if test_weights is not None:
                raise ValueError("test_weights= given but calibration had no weights")
            table = self.thresholds_ if self._grouped else self.thresholds_.unsqueeze(0)
            threshold = table[idx]
        threshold = torch.where(
            known.unsqueeze(-1), threshold, torch.full_like(threshold, math.inf)
        )

        with torch.no_grad():
            state = self.score._prepare(predictive)
        return JointRegion(
            predictive, self.score, self.alpha, threshold, state, self._masked, self._scalar
        )


