def _check_y(predictive: JointPredictive, y: Any) -> Tensor:
    """``y`` (tensor or array) in the predictive's dtype and on its device, shape-checked."""
    y = predictive.as_input(y)
    n, d = predictive.batch_size, predictive.event_dim
    if y.dim() not in (2, 3) or y.shape[0] != n or y.shape[-1] != d:
        raise ValueError(
            f"y must be [n, d] or [n, S, d] with n = {n} and d = {d}, got {tuple(y.shape)}"
        )
    return y


def _check_mask(predictive: JointPredictive, mask: Any, like: Tensor) -> Tensor:
    mask = torch.as_tensor(mask)
    shape = (predictive.batch_size, predictive.event_dim)
    if mask.dtype != torch.bool or tuple(mask.shape) != shape:
        raise ValueError(
            f"mask must be boolean [n, d] = {list(shape)}, got {mask.dtype} {tuple(mask.shape)}"
        )
    return mask.to(like.device)


def _nan_as_inf(scores: Tensor) -> Tensor:
    """``NaN`` scores become ``+inf`` (other values, ``+inf`` included, are kept)."""
    return torch.where(torch.isnan(scores), torch.full_like(scores, math.inf), scores)


def _as_3d(y: Tensor) -> Tensor:
    return y if y.dim() == 3 else y.unsqueeze(1)


def _like_input(out: Tensor, y: Tensor) -> Tensor:
    """Drop the sample axis of ``out [n, S]`` when ``y`` was ``[n, d]``."""
    return out if y.dim() == 3 else out[:, 0]


def _order_stat_thresholds(scores: Tensor, alphas: Sequence[float]) -> Tensor:
    """Unweighted split-conformal thresholds ``[L]`` (``+inf`` for no scores).

    One :func:`~torchregress.losses.conformal.finite_sample_quantile` per level: the
    order statistic of rank ``ceil((n + 1)(1 - alpha))``, ``+inf`` past ``n``.
    """
    if scores.numel() == 0:
        return torch.full((len(alphas),), math.inf, dtype=scores.dtype, device=scores.device)
    return torch.stack([finite_sample_quantile(scores, a).to(scores.dtype) for a in alphas])


def _weighted_thresholds(
    scores: Tensor, weights: Tensor, test_weights: Optional[Tensor], alphas: Sequence[float]
) -> Tensor:
    r"""Weighted thresholds ``[r, L]`` for ``r`` test weights (``[1, L]`` for the mean weight).

    The Tibshirani et al. (2019) quantile of
    :math:`\sum_i p_i \delta_{s_i} + p_{n+1} \delta_{+\infty}` computed by the
    shipped weighted helper of :mod:`torchregress.losses.conformal`, one level
    at a time; ``+inf`` when there are no scores or no calibration weight.
    """
    r = 1 if test_weights is None else int(test_weights.numel())
    if scores.numel() == 0 or not float(weights.sum()) > 0.0:
        return torch.full((r, len(alphas)), math.inf, dtype=scores.dtype, device=scores.device)
    cols = [
        _weighted_conformal_thresholds(scores, 1.0 - a, weights, test_weights).to(scores.dtype)
        for a in alphas
    ]
    return torch.stack(cols, dim=-1)


