r"""Joint conformal prediction regions for any :class:`JointPredictive`.

A joint region :math:`R(x) \subset \mathbb R^d` is built by split conformal
calibration of one scalar conformity score :math:`s(x, y)` (small = typical
under the predictive).  On a calibration set :math:`(x_i, y_i)_{i=1}^n` with
scores :math:`s_i = s(x_i, y_i)` the threshold is

.. math::
    \hat t_\alpha = s_{(k)}, \qquad k = \lceil (n + 1)(1 - \alpha) \rceil,

the :math:`k`-th smallest score (:math:`+\infty` when :math:`k > n`), and

.. math::
    R_\alpha(x) = \{\, y : s(x, y) \le \hat t_\alpha \,\}.

**Guarantee.**  If the calibration pairs and the test pair
:math:`(X_{n+1}, Y_{n+1})` are exchangeable, then

.. math::
    P\big(Y_{n+1} \in R_\alpha(X_{n+1})\big) \ge 1 - \alpha,

and, when the scores are almost surely distinct (continuous scores),
:math:`P(Y_{n+1} \in R_\alpha(X_{n+1})) \le 1 - \alpha + 1/(n + 1)`.  The
probability is over the calibration set *and* the test pair: this is
*marginal* coverage, not coverage at each individual :math:`x`.  It holds
whatever the quality of the predictive (a mis-specified model gives a larger
region, not a lower coverage).  Several levels ``alpha`` give nested regions
by construction, since the order statistic is monotone in :math:`\alpha`.

Extensions:

* **Weighted** (Tibshirani et al. 2019): with calibration weights
  :math:`w_i \ge 0` and test weight :math:`w_{n+1}` (for covariate shift,
  :math:`w(x) = dP_{\text{test}}/dP_{\text{cal}}(x)`), the threshold is the
  :math:`(1-\alpha)`-quantile of
  :math:`\sum_i p_i \delta_{s_i} + p_{n+1} \delta_{+\infty}` with
  :math:`p_i = w_i / \sum_{j=1}^{n+1} w_j`.  Coverage
  :math:`\ge 1 - \alpha` holds under covariate shift with the true
  likelihood ratio.
* **Mondrian** (Vovk et al. 2005): one threshold per group, so that
  :math:`P(Y \in R(X) \mid G = g) \ge 1 - \alpha` for every group :math:`g`.
* **Missing calibration targets**: scores that accept a mask are computed on
  the observed sub-vector; the guarantee then holds for test points whose
  missingness is generated by the same mechanism as in calibration
  (Braun et al. 2025).

Scores (``score(predictive, y)`` with ``y [n, d] -> [n]``, ``[n, S, d] -> [n, S]``):

* :class:`DensityScore`: density level set (DR-CP); needs ``has_density``.
* :class:`HPDScore`: HPD level set (HPD-split, C-HDR); density and draws.
* :class:`LatentScore`: pre-image of a latent ball (L-CP); needs ``has_latent``.
* :class:`MahalanobisScore`: ellipsoid from ``mean()`` and ``covariance()``.
* :class:`MaxResidualScore`: box with a joint guarantee, same moments.
* :class:`SampleBallScore`: union of balls around draws (PCP); draws only.

Monte Carlo scores (:class:`HPDScore`, :class:`SampleBallScore`) are valid
only when calibration and test scores are computed the same way: each
:class:`JointRegion` draws its own reference set once, with the same
``n_samples`` stored on the score as in calibration, so its membership test is
deterministic.

References:
    - Lei, G'Sell, Rinaldo, Tibshirani, Wasserman (2018). Distribution-free
      predictive inference for regression. JASA 113.
    - Izbicki, Shimizu, Stern (2022). CD-split and HPD-split: efficient
      conformal regions in high dimensions. JMLR 23.
    - Dheur, Fontana, Estievenart, Ben Taieb (2025). Multi-output conformal
      regression: a unified comparative study with new conformity scores.
      ICML (arXiv:2501.10533).
    - Braun et al. (2025). Multivariate standardized residuals for conformal
      prediction (arXiv:2507.20941).
    - Wang, Gao, Yin, Zhou, Blei (2023). Probabilistic conformal prediction
      using conditional random samples. AISTATS.
    - Tibshirani, Barber, Candès, Ramdas (2019). Conformal prediction under
      covariate shift. NeurIPS.
    - Vovk, Gammerman, Shafer (2005). Algorithmic Learning in a Random World
      (Mondrian conformal predictors).
    - Schlembach, Smirnov, Winands (2026). Corrected max-rank multi-target
      conformal regions. COPA.
"""

