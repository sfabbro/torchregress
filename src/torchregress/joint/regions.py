class ConformalScore(ABC):
    """Conformity score :math:`s(x, y)`: small means typical under the predictive.

    Subclasses implement :meth:`_evaluate`, and :meth:`_prepare` when the score
    needs per-row reference quantities (draws, moments).  A
    :class:`JointRegion` prepares them once and keeps them, so its membership
    test is a fixed function of ``y``.
    """

    name: str = "score"
    #: The score accepts a missing-target mask (``True`` = observed).
    supports_mask: bool = False

    def check(self, predictive: JointPredictive) -> None:
        """Raise a clear error if the predictive lacks a needed capability."""

    def check_mask(self, predictive: JointPredictive) -> None:
        """Raise if the score cannot handle missing targets for this predictive."""
        if not self.supports_mask:
            raise ValueError(f"{type(self).__name__} does not support missing-target masks")

    def score(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor] = None
    ) -> Tensor:
        """Scores: ``y [n, d] -> [n]``, ``y [n, S, d] -> [n, S]``.

        Monte Carlo scores draw a fresh reference set on every call.
        """
        self.check(predictive)
        y = _check_y(predictive, y)
        if mask is not None:
            self.check_mask(predictive)
            mask = _check_mask(predictive, mask, y)
        with torch.no_grad():
            return self._evaluate(predictive, y, mask, self._prepare(predictive))

    def _prepare(self, predictive: JointPredictive) -> _State:
        return {}

    @abstractmethod
    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        """Scores of ``y`` given the prepared ``state``."""

    def _closed_log_volume(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[Tensor]:
        """Closed-form log-volume ``[n, L]`` of the region, if any."""
        return None

    def _closed_box(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[tuple[Tensor, Tensor]]:
        """Exact bounding box ``([n, L, d], [n, L, d])``, if any."""
        return None

    def __repr__(self) -> str:
        return f"{type(self).__name__}()"


class DensityScore(ConformalScore):
    r"""Negative log density, :math:`s(x, y) = -\log \hat p(y \mid x)` (DR-CP).

    The region is a density level set
    :math:`\{y : \hat p(y \mid x) \ge e^{-\hat t}\}`, the smallest-volume region
    when the predictive is correct (Lei et al. 2018; Dheur et al. 2025).  With a
    mask the score is the negative log density of the observed sub-vector, which
    needs a predictive with ``exact_marginals``.  The threshold is shared across
    rows, so rows with a broad predictive get a low density level; for an
    adaptive level use :class:`HPDScore`.
    """

    name = "density"
    supports_mask = True

    def check(self, predictive: JointPredictive) -> None:
        if not predictive.has_density:
            raise ValueError(
                f"DensityScore needs a predictive with a density; {predictive!r} has none"
            )

    def check_mask(self, predictive: JointPredictive) -> None:
        if not predictive.exact_marginals:
            raise ValueError(
                "DensityScore with a mask needs a predictive with exact_marginals; "
                f"{predictive!r} cannot integrate out missing targets"
            )

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        return -predictive.log_prob(y, mask)


class HPDScore(ConformalScore):
    r"""Highest-predictive-density level (HPD-split, C-HDR).

    .. math::
        s(x, y) = h(x, y) = P_{Y' \sim \hat p(\cdot \mid x)}
        \big[\hat p(Y' \mid x) > \hat p(y \mid x)\big] \in [0, 1],

    estimated from ``n_samples`` reference draws per row (ties count one half).
    The region is the HPD set of :math:`\hat p(\cdot \mid x)` with mass
    :math:`\hat t`, so its density level adapts to each row (Izbicki, Shimizu,
    Stern 2022).  The estimate is Monte Carlo: calibration and test scores must
    use the same ``n_samples``, which is why it is stored here.

    The Monte Carlo level takes only the values :math:`j / (2M)`; when the
    predictive is too narrow many calibration points sit above every draw and
    share :math:`h = 1`, and the region would then be the whole space.  Ties are
    broken deterministically by the density,

    .. math::
        s(x, y) = \hat h(x, y) + \frac{1}{2M}\Big(\tfrac12
        + \tfrac1\pi \arctan\big(-\log \hat p(y \mid x)\big)\Big),

    which is strictly increasing in :math:`-\log \hat p(y \mid x)` within a
    row (so the region is still an HPD set) and within :math:`1/(2M)` of
    :math:`\hat h`.

    Args:
        n_samples: Reference draws per row.
    """

    name = "hpd"

    def __init__(self, n_samples: int = 256) -> None:
        if n_samples < 1:
            raise ValueError(f"n_samples must be positive, got {n_samples}")
        self.n_samples = int(n_samples)

    def check(self, predictive: JointPredictive) -> None:
        if not predictive.has_density:
            raise ValueError(f"HPDScore needs a predictive with a density; {predictive!r} has none")

    def _prepare(self, predictive: JointPredictive) -> _State:
        draws = predictive.sample(self.n_samples)
        ref = predictive.log_prob(draws)
        return {"ref": ref.sort(dim=1).values.contiguous()}

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        ref = state["ref"]
        lp = predictive.log_prob(y)
        lp2 = (lp if y.dim() == 3 else lp.unsqueeze(1)).to(ref).contiguous()
        right = torch.searchsorted(ref, lp2, right=True)
        left = torch.searchsorted(ref, lp2)
        m = ref.shape[1]
        h = ((m - right) + 0.5 * (right - left)).to(ref.dtype) / m
        tie_break = (0.5 + torch.atan(-lp2) / math.pi) / (2 * m)
        return _like_input(h + tie_break, y)

    def __repr__(self) -> str:
        return f"HPDScore(n_samples={self.n_samples})"


class LatentScore(ConformalScore):
    r"""Latent norm, :math:`s(x, y) = \lVert T^{-1}(y; x) \rVert_2` (L-CP).

    :math:`T^{-1}` is the predictive's map to a standard-normal latent space
    (``to_latent``).  The region is the pre-image of a latent ball of radius
    :math:`\hat t`; for a Gaussian predictive it is the Mahalanobis ellipsoid.
    Exact and about a hundred times cheaper than sampling scores (Dheur et al.
    2025).
    """

    name = "latent"

    def check(self, predictive: JointPredictive) -> None:
        if not predictive.has_latent:
            raise ValueError(
                f"LatentScore needs a predictive with a latent map; {predictive!r} has none"
            )

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        return torch.linalg.vector_norm(predictive.to_latent(y), dim=-1)


class MahalanobisScore(ConformalScore):
    r"""Standardized residual (ellipsoid), from the predictive mean and covariance.

    Without a mask,

    .. math::
        s(x, y) = \sqrt{(y - m)^\top \Sigma^{-1} (y - m)},
        \qquad m = \hat{\mathbb E}[Y \mid x],\ \Sigma = \widehat{\mathrm{Cov}}[Y \mid x].

    With a mask (observed set :math:`O`, :math:`k = |O|`) the quadratic form of
    the observed sub-vector is mapped through the :math:`\chi^2_k` CDF,

    .. math::
        s(x, y) = F_{\chi^2_k}\big((y_O - m_O)^\top \Sigma_{OO}^{-1} (y_O - m_O)\big),

    so that rows with different numbers of observed targets share one scale
    (Braun et al. 2025).  The guarantee then holds for test points with the same
    missingness mechanism.  A region calibrated with a mask keeps this scale at
    test time (a test row without a mask is treated as fully observed).
    The :math:`\chi^2` CDF saturates near one in single precision; use
    ``float64`` for large ``d``.  For heads whose moments are Monte Carlo the
    moments are drawn once per call (calibration) and once per region (test).
    """

    name = "mahalanobis"
    supports_mask = True

    def _prepare(self, predictive: JointPredictive) -> _State:
        mean = predictive.mean()
        cov = predictive.covariance()
        return {"mean": mean, "cov": cov, "chol": torch.linalg.cholesky(cov)}

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        mean, cov = state["mean"].to(y), state["cov"].to(y)
        resid = _as_3d(y) - mean.unsqueeze(1)
        if mask is None:
            z = torch.linalg.solve_triangular(state["chol"].to(y), resid.mT, upper=False).mT
            return _like_input(z.square().sum(-1).sqrt(), y)
        # Exact marginalisation of the missing targets (known_covariance_gaussian_nll).
        quad, _, k = masked_gaussian_quadratic(resid, cov, mask)
        cdf = torch.special.gammainc((0.5 * k).clamp(min=0.5), 0.5 * quad)
        return _like_input(torch.where(k > 0, cdf, torch.zeros_like(cdf)), y)

    @staticmethod
    def _radius(threshold: Tensor, masked: bool, d: int) -> Tensor:
        if not masked:
            return threshold
        level = threshold.detach().cpu().double().clamp(min=0.0, max=1.0).numpy()
        r2 = torch.as_tensor(chi2.ppf(level, d), dtype=threshold.dtype, device=threshold.device)
        return r2.sqrt()

    def _closed_log_volume(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[Tensor]:
        d = int(state["mean"].shape[-1])
        r = self._radius(threshold, masked, d)
        log_ball = 0.5 * d * math.log(math.pi) - math.lgamma(0.5 * d + 1.0)
        half_log_det = state["chol"].diagonal(dim1=-2, dim2=-1).log().sum(-1).to(r)
        return log_ball + d * r.log() + half_log_det.unsqueeze(-1)

    def _closed_box(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[tuple[Tensor, Tensor]]:
        d = int(state["mean"].shape[-1])
        r = self._radius(threshold, masked, d).unsqueeze(-1)  # [n, L, 1]
        mean = state["mean"].to(r).unsqueeze(1)
        half = r * state["cov"].diagonal(dim1=-2, dim2=-1).sqrt().to(r).unsqueeze(1)
        return mean - half, mean + half


class MaxResidualScore(ConformalScore):
    r"""Largest standardized absolute residual (a box with a joint guarantee).

    .. math::
        s(x, y) = \max_j \frac{\lvert y_j - m_j \rvert}{s_j},
        \qquad s_j = \sqrt{\Sigma_{jj}},

    with the maximum over observed targets only under a mask.  The region is the
    box :math:`\prod_j [m_j - \hat t s_j, m_j + \hat t s_j]`.

    Why one calibrated maximum gives a *joint* guarantee:
    :math:`Y \in \text{box}` if and only if :math:`s(X, Y) \le \hat t`, and the
    conformal argument applies to that single scalar, so
    :math:`P(\text{all } d \text{ targets inside}) \ge 1 - \alpha`.  Calibrating
    each target separately at :math:`1 - \alpha` only controls each marginal;
    the probability that *all* are covered is only bounded below by
    :math:`1 - d\alpha` (Bonferroni) and falls short of :math:`1 - \alpha`
    unless the targets are perfectly dependent.

    The *max-rank* variant (rank each target's residual first, then take the
    maximum rank) needs the corrected order statistic of Schlembach, Smirnov and
    Winands (COPA 2026): the usual score-space implementation is one order
    statistic too small.  Max-rank is not implemented here.
    """

    name = "max_residual"
    supports_mask = True

    def _prepare(self, predictive: JointPredictive) -> _State:
        mean = predictive.mean()
        std = predictive.covariance().diagonal(dim1=-2, dim2=-1).sqrt()
        return {"mean": mean, "std": std}

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        mean, std = state["mean"].to(y), state["std"].to(y)
        r = (_as_3d(y) - mean.unsqueeze(1)).abs() / std.unsqueeze(1)
        if mask is not None:
            r = torch.where(mask.unsqueeze(1), r, torch.zeros_like(r))
        return _like_input(r.amax(dim=-1), y)

    def _closed_log_volume(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[Tensor]:
        log_std = state["std"].to(threshold).log().sum(-1, keepdim=True)  # [n, 1]
        d = int(state["std"].shape[-1])
        return d * (2.0 * threshold).log() + log_std

    def _closed_box(
        self, state: _State, threshold: Tensor, masked: bool
    ) -> Optional[tuple[Tensor, Tensor]]:
        t = threshold.unsqueeze(-1)  # [n, L, 1]
        mean = state["mean"].to(t).unsqueeze(1)
        half = t * state["std"].to(t).unsqueeze(1)
        return mean - half, mean + half


class SampleBallScore(ConformalScore):
    r"""Distance to the nearest predictive draw (PCP; Wang et al. 2023).

    .. math::
        s(x, y) = \min_{k \le K} \lVert y - \hat Y_k \rVert_2,
        \qquad \hat Y_k \sim \hat p(\cdot \mid x),

    so the region is a union of :math:`K` balls of radius :math:`\hat t`.  It
    needs only draws (implicit generators, forests).  Monte Carlo: calibration
    draws a fresh set per call; a :class:`JointRegion` draws ``n_samples`` once
    and keeps them, so calibration and test scores are computed the same way
    and membership is deterministic.

    Args:
        n_samples: Draws per row, :math:`K`.
    """

    name = "sample_ball"

    def __init__(self, n_samples: int = 64) -> None:
        if n_samples < 1:
            raise ValueError(f"n_samples must be positive, got {n_samples}")
        self.n_samples = int(n_samples)

    def _prepare(self, predictive: JointPredictive) -> _State:
        return {"draws": predictive.sample(self.n_samples).clone()}

    def _evaluate(
        self, predictive: JointPredictive, y: Tensor, mask: Optional[Tensor], state: _State
    ) -> Tensor:
        draws = state["draws"].to(y)
        y3 = _as_3d(y)
        n, s, _ = y3.shape
        chunk = max(1, _CHUNK_ELEMS // max(1, n * draws.shape[1]))
        parts = [torch.cdist(y3[:, i : i + chunk], draws).amin(dim=-1) for i in range(0, s, chunk)]
        return _like_input(torch.cat(parts, dim=1), y)

    def __repr__(self) -> str:
        return f"SampleBallScore(n_samples={self.n_samples})"


