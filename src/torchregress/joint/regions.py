class JointRegion:
    r"""Calibrated joint regions :math:`R_\alpha(x_i) = \{y : s(x_i, y) \le t_i\}`.

    Built by :meth:`JointConformal.region`; one region per row and level.

    **Targets of interest and nuisance targets.**  To obtain a region for a
    subset of targets only (integrating out the nuisance ones), calibrate and
    build the region on ``predictive.marginal(dims)`` with targets
    ``y[:, dims]``.  The guarantee then applies to the sub-vector ``y[:, dims]``.

    Attributes:
        predictive: Predictive of the rows.
        score: The conformity score.
        alpha: Level(s), as given to :class:`JointConformal`.
        threshold: ``[n, L]`` per-row thresholds (after weights and groups).
        mask_region: Optional region used by :meth:`contains` when a mask is
            passed (set by :meth:`JointRegressor.region
            <torchregress.joint.JointRegressor.region>` when the conformal rows
            had missing targets: this region is then calibrated on complete rows
            and ``mask_region`` on the masked scores).

    A score that is ``NaN`` (a failed evaluation) counts as ``+inf``, in
    calibration and in membership alike: such a point is outside every region
    with a finite threshold and inside a region whose threshold is ``+inf``.
    """

    def __init__(
        self,
        predictive: JointPredictive,
        score: ConformalScore,
        alpha: Union[float, Sequence[float]],
        threshold: Tensor,
        state: _State,
        masked: bool,
        scalar: bool,
    ) -> None:
        self.predictive = predictive
        self.score = score
        self.alpha = alpha
        self.threshold = threshold
        self._state = state
        self._masked = masked
        self._scalar = scalar
        self.mask_region: Optional[JointRegion] = None

    @property
    def n_levels(self) -> int:
        return int(self.threshold.shape[1])

    def _squeeze(self, out: Tensor, axis: int) -> Tensor:
        return out.select(axis, 0) if self._scalar else out

    def _level(self, level: Optional[int]) -> int:
        if level is None:
            if self.n_levels != 1:
                raise ValueError("several levels: pass level= (an index into alpha)")
            return 0
        if not 0 <= level < self.n_levels:
            raise ValueError(f"level must be in [0, {self.n_levels}), got {level}")
        return level

    def _scores(self, y: Tensor, mask: Optional[Tensor] = None) -> Tensor:
        if self._masked and mask is None:
            mask = torch.ones(
                self.predictive.batch_size,
                self.predictive.event_dim,
                dtype=torch.bool,
                device=y.device,
            )
        with torch.no_grad():
            return _nan_as_inf(self.score._evaluate(self.predictive, y, mask, self._state))

    def _inside(self, y: Tensor) -> Tensor:
        """Membership of fully observed ``y [n, S, d]``: ``[n, S, L]``."""
        s = self._scores(y)
        return s.unsqueeze(-1) <= self.threshold.to(s).unsqueeze(1)

    def contains(self, y: Tensor, mask: Optional[Tensor] = None) -> Tensor:
        """Membership: ``y [n, d] -> [n, L]``, ``[n, S, d] -> [n, S, L]``.

        The level axis ``L`` is dropped for a scalar ``alpha``.

        Args:
            y: Targets.
            mask: Boolean ``[n, d]`` (``True`` = observed); only for a region
                calibrated with a mask.  A row with nothing observed is inside.
        """
        y = _check_y(self.predictive, y)
        if mask is not None and self.mask_region is not None:
            return self.mask_region.contains(y, mask)
        if mask is not None:
            if not self._masked:
                raise ValueError("this region was calibrated without a mask; pass none")
            mask = _check_mask(self.predictive, mask, y)
        s = self._scores(y, mask)
        t = self.threshold.to(s)
        inside = s.unsqueeze(-1) <= (t if y.dim() == 2 else t.unsqueeze(1))
        if mask is not None:
            empty = ~mask.any(-1)
            empty = empty.unsqueeze(-1) if y.dim() == 2 else empty[:, None, None]
            inside = inside | empty
        return self._squeeze(inside, -1)

    def log_volume(self, n_samples: int = 1024) -> tuple[Tensor, Tensor]:
        r"""Log Lebesgue volume of each region and its standard error, ``[n]`` or ``[n, L]``.

        Closed forms for the Mahalanobis ellipsoid
        (:math:`\log V = \log V_d + d \log r + \tfrac12 \log\det\Sigma`, with
        :math:`V_d` the unit-ball volume) and the max-residual box
        (:math:`\sum_j \log(2 \hat t s_j)`); their standard error is zero.
        Otherwise importance sampling from the predictive (Dheur et al. 2025),

        .. math::
            \hat V = \frac1K \sum_{k=1}^K
            \frac{\mathbf 1[Y_k \in R]}{\hat p(Y_k \mid x)},
            \qquad Y_k \sim \hat p(\cdot \mid x),

        unbiased for the volume of :math:`R \cap \mathrm{supp}\,\hat p`, with the
        delta-method standard error
        :math:`\mathrm{se}(\log \hat V) = \mathrm{sd}(w_k) / (\sqrt K\, \bar w)`.
        When the region reaches far into the tails of :math:`\hat p` (a
        predictive that is too narrow) the weights are heavy-tailed: the
        estimate is then biased low and its standard error too small.  For
        predictives with a latent map the proposal is therefore a defensive
        mixture: one third of the draws from :math:`\hat p` and the rest from
        the push-forward of latent normals with scale 2 and 4, weighted by the
        mixture density (deterministic-mixture importance sampling, Owen and
        Zhou 2000).
        For a :class:`SampleBallScore` on a predictive without density the
        volume is estimated by uniform sampling in the bounding box of the
        balls (accurate in low ``d`` only).  ``+inf`` for an infinite threshold;
        ``-inf`` (standard error ``nan``) when no draw falls inside.
        """
        t = self.threshold
        closed = self.score._closed_log_volume(self._state, t, self._masked)
        if closed is not None:
            est, se = closed, torch.zeros_like(closed)
        elif self.predictive.has_density:
            est, se = self._importance_log_volume(n_samples)
        elif isinstance(self.score, SampleBallScore):
            est, se = self._box_mc_log_volume(n_samples)
        else:
            raise ValueError(
                f"no closed-form volume for {self.score!r} and {self.predictive!r} has no "
                "density for importance sampling"
            )
        infinite = torch.isinf(t) & (t > 0)
        est = torch.where(infinite.to(est.device), torch.full_like(est, math.inf), est)
        se = torch.where(infinite.to(se.device), torch.zeros_like(se), se)
        return self._squeeze(est, -1), self._squeeze(se, -1)

    def _importance_log_volume(self, n_samples: int) -> tuple[Tensor, Tensor]:
        with torch.no_grad():
            if self.predictive.has_latent:
                draws, log_q = self._latent_mixture_draws(n_samples)
            else:
                draws = self.predictive.sample(n_samples)
                log_q = self.predictive.log_prob(draws)  # [n, K]
            inside = self._inside(draws) & torch.isfinite(log_q).unsqueeze(-1)  # [n, K, L]
        neg = (-log_q).unsqueeze(-1).expand_as(inside)
        terms = torch.where(inside, neg, torch.full_like(neg, -math.inf))
        est = torch.logsumexp(terms, dim=1) - math.log(n_samples)  # [n, L]
        ratio = (terms - est.unsqueeze(1)).exp()  # w_k / mean(w)
        se = ratio.std(dim=1) / math.sqrt(n_samples)
        return est, se

    def _latent_mixture_draws(self, n_samples: int) -> tuple[Tensor, Tensor]:
        r"""Draws and log proposal density for the defensive latent-scale mixture.

        Latent draws :math:`z_k \sim \mathcal N(0, c_k^2 I)` with the scales
        :math:`c \in \{1, 2, 4\}` allocated in turn (fractions :math:`\pi_c`),
        pushed through ``from_latent``.  With :math:`r^2 = \lVert z \rVert^2`,
        :math:`q(y) / \hat p(y) = \sum_c \pi_c\, c^{-d} \exp\big(r^2 (1 - c^{-2}) / 2\big)`.
        """
        probe = self.predictive.sample(1)
        n, d = self.predictive.batch_size, self.predictive.event_dim
        scales = torch.tensor(_IS_LATENT_SCALES, dtype=probe.dtype, device=probe.device)
        component = torch.arange(n_samples, device=probe.device) % scales.numel()
        # Actual allocation fractions keep the estimator unbiased for any K.
        log_frac = (torch.bincount(component, minlength=scales.numel()).to(probe) / n_samples).log()
        z = torch.randn(n, n_samples, d, dtype=probe.dtype, device=probe.device)
        z = z * scales[component].view(1, -1, 1)
        draws = self.predictive.from_latent(z)
        lp = self.predictive.log_prob(draws)
        r2 = z.square().sum(-1, keepdim=True)  # [n, K, 1]
        log_ratio = torch.logsumexp(
            log_frac - d * scales.log() + 0.5 * r2 * (1.0 - scales.pow(-2)), dim=-1
        )
        return draws, lp + log_ratio

    def _box_mc_log_volume(self, n_samples: int) -> tuple[Tensor, Tensor]:
        draws = self._state["draws"]
        n, _, d = draws.shape
        ests, ses = [], []
        for level in range(self.n_levels):
            t = self.threshold[:, level].to(draws).unsqueeze(-1)  # [n, 1]
            lo = draws.amin(dim=1) - t
            hi = draws.amax(dim=1) + t
            u = torch.rand(n, n_samples, d, device=draws.device, dtype=draws.dtype)
            pts = lo.unsqueeze(1) + (hi - lo).unsqueeze(1) * u
            inside = self._scores(pts) <= t
            frac = inside.to(draws.dtype).mean(dim=1)
            ests.append((hi - lo).log().sum(-1) + frac.log())
            ses.append(((1.0 - frac) / (n_samples * frac)).sqrt())
        return torch.stack(ests, dim=-1), torch.stack(ses, dim=-1)

    def _propose(self, n_draws: int, level: int) -> tuple[Tensor, Tensor]:
        """One rejection round: candidate draws ``[n, B, d]`` and which are kept ``[n, B]``."""
        with torch.no_grad():
            draws = self.predictive.sample(n_draws)
        return draws, self._inside(draws)[..., level]

    def sample(
        self, n_samples: int, *, level: Optional[int] = None, max_rounds: int = 50
    ) -> Tensor:
        """Draws ``[n, S, d]`` from the predictive restricted to the region.

        Rejection sampling: batches of ``2 S`` predictive draws per round are
        kept when inside the region, for at most ``max_rounds`` rounds.
        Fallback when acceptance is tiny: a row that is still short is filled
        by resampling its accepted draws with replacement (no longer
        independent), and a row with no accepted draw is filled with ``nan``;
        both cases emit a ``RuntimeWarning``.

        Args:
            n_samples: Draws per row ``S``.
            level: Index into ``alpha`` (required with several levels).
            max_rounds: Rejection rounds.
        """
        lvl = self._level(level)
        n, d = self.predictive.batch_size, self.predictive.event_dim
        out: Optional[Tensor] = None
        count: Optional[Tensor] = None
        for _ in range(max_rounds):
            draws, inside = self._propose(2 * n_samples, lvl)  # [n, B, d], [n, B]
            if out is None or count is None:
                out = torch.full(
                    (n, n_samples, d), math.nan, dtype=draws.dtype, device=draws.device
                )
                count = torch.zeros(n, dtype=torch.long, device=draws.device)
            rank = inside.long().cumsum(dim=1) - 1 + count.unsqueeze(1)
            keep = inside & (rank < n_samples)
            rows, cols = keep.nonzero(as_tuple=True)
            out[rows, rank[rows, cols]] = draws[rows, cols]
            count = count + keep.sum(dim=1)
            if bool((count >= n_samples).all()):
                break
        assert out is not None and count is not None
        short = count < n_samples
        if bool(short.any()):
            warnings.warn(
                f"{int(short.sum())} row(s) accepted fewer than {n_samples} draws in "
                f"{max_rounds} rounds; resampling accepted draws (nan where none)",
                RuntimeWarning,
                stacklevel=2,
            )
            pos = torch.arange(n_samples, device=out.device).unsqueeze(0)
            src = torch.rand(n, n_samples, device=out.device) * count.clamp(min=1).unsqueeze(1)
            src = src.long().clamp(max=n_samples - 1)
            filled = torch.gather(out, 1, src.unsqueeze(-1).expand(n, n_samples, d))
            need = (pos >= count.unsqueeze(1)) & (count > 0).unsqueeze(1)
            out = torch.where(need.unsqueeze(-1), filled, out)
        return out

    def bounding_box(self, n_samples: int = 2048) -> tuple[Tensor, Tensor]:
        """Lower and upper corners ``[n, d]`` (``[n, L, d]`` with several levels).

        Exact for the box and the ellipsoid.  Otherwise the coordinate-wise
        range of ``n_samples`` accepted draws (:meth:`sample`), an inner
        estimate of the true box; ``-inf``/``+inf`` for an infinite threshold.
        """
        closed = self.score._closed_box(self._state, self.threshold, self._masked)
        if closed is not None:
            lower, upper = closed
        else:
            lows, ups = [], []
            for level in range(self.n_levels):
                draws = self.sample(n_samples, level=level)
                lows.append(draws.amin(dim=1))
                ups.append(draws.amax(dim=1))
            lower, upper = torch.stack(lows, dim=1), torch.stack(ups, dim=1)
            infinite = (torch.isinf(self.threshold) & (self.threshold > 0)).unsqueeze(-1)
            infinite = infinite.to(lower.device)
            lower = torch.where(infinite, torch.full_like(lower, -math.inf), lower)
            upper = torch.where(infinite, torch.full_like(upper, math.inf), upper)
        return self._squeeze(lower, 1), self._squeeze(upper, 1)

    def __repr__(self) -> str:
        return (
            f"JointRegion(score={self.score!r}, alpha={self.alpha}, "
            f"n={self.predictive.batch_size}, d={self.predictive.event_dim})"
        )
